<h1>Criterios de catalogación</h1>

<section>
  <h2>Unidad de catalogación</h2>
  <p>
    RePoMIt trabaja siempre con testimonios manuscritos completos. La catalogación no
    parte de poemas aislados, sino de la secuencia de composiciones transmitida por cada
    manuscrito. Sin embargo, en caso de florilegios plurilingüe, la catalogación se limita
    a los poemas en idioma castellano y a los poemas plurilingües entre cuyos idiomas se
    incluya el castellano.
  </p>
</section>

<section>
  <h2>El ítem</h2>
  <p>
    El ítem o código identificativo de cada composición catalogada se forma mediante la
    sigla del testimonio y el orden topográfico de la composición dentro del manuscrito.
    Este criterio permite conservar la relación entre la ficha poética y la estructura
    dispositiva del testimonio.
  </p>
  <p>
    La sigla de cada testimonio es el resultado de la unión de los datos siguientes:
    Ciudad (primeras dos letras), Biblioteca u otra institución (primera letra), Fondo
    (primera letra), Signatura.
  </p>
</section>

<section>
  <h2>Campos de la ficha</h2>
  <p>
    Las fichas de los poemas recogen los siguientes datos: <strong>Íncipit</strong>,
    <strong>Segundo verso</strong>, <strong>Éxplicit</strong>,
    <strong>Testimonio</strong> (incluidos el orden topográfico y los folios/páginas que
    ocupa en él; si se trata de folios, se incluye también la indicación del recto/verso),
    <strong>Epígrafe</strong>, <strong>Atribución</strong> (declarada en el testimonio o
    reconstruida por los estudios críticos y/o por otras fuentes documentales),
    <strong>Forma métrico-poética</strong>, <strong>Esquema métrico</strong>,
    <strong>Estructura</strong> (estrofas de desarrollo a partir de una letra/mote inicial,
    composiciones internas y/o finales, estribillos), <strong>Transcripción</strong> del
    texto de la composición y <strong>Responsabilidad de la ficha</strong>.
  </p>
  <p>
    Las fichas de los testimonios incluyen los siguientes datos: <strong>Ciudad</strong>,
    <strong>Institución</strong>, <strong>Signatura</strong>, <strong>Recopilador</strong>,
    <strong>Fecha</strong>, <strong>Contenido</strong> y <strong>Bibliografía</strong>.
  </p>
  <p>
    Lo que aparece entre corchetes [ ] procede de una conjetura del responsable de la
    ficha o de la bibliografía consultada y mencionada en la ficha del testimonio al que
    se corresponde la composición.
  </p>
  <p>
    El campo de la Transcripción es facultativo, menos en los casos en los que el texto
    catalogado presente variación textual en el propio testimonio que se está catalogando.
    En este caso, los otros campos del repertorio acogen la versión textual definitiva
    mientras que la transcripción se configura como el lugar en el que se da cuenta de las
    distintas fases de escritura y corrección/cambio.
  </p>
</section>

<section>
  <h2>Opciones de búsqueda</h2>
  <p>
    La búsqueda ignora puntuación, mayúsculas y tildes. Esto permite localizar variantes
    gráficas de un mismo verso sin exigir coincidencia literal estricta.
  </p>
  <p>
    La grafía de los poemas, salvo excepciones justificadas (ej. italianismos y lusitanismos
    que, por distintos motivos, no se pueden remitir al término castellano correspondiente),
    sigue las normas ortográficas actuales.
  </p>
  <p>
    La búsqueda por Íncipit consulta tres campos: el íncipit de la composición y, cuando
    constan, también el íncipit de la primera estrofa de desarrollo y el de eventuales
    composiciones internas y/o finales.
  </p>
  <p>
    La sección relativa a la forma métrico-poética se basa en el uso de un vocabulario
    controlado que trata de contrarrestar la significativa variabilidad taxonómica de la
    poesía de los Siglos de Oro y su excepcional oscilación en la denominación de las
    formas. Por tanto, las formas catalogadas se reducen a las siguientes (en orden
    alfabético): Canción en arte menor (incluye todas las formas de canción en octosílabos
    u otros versos de arte menor; ej. redondillas, quintillas, copla real, canción
    trovadoresca, décima espinela, etc. NB no incluye las glosas); Canción en arte mayor;
    Canción petrarquista (incluye todas las formas de canciones en las que se alternan
    endecasílabos y heptasílabos; ej. cuarteto-lira, lira garcilasiana, lira-sextina/sexteto-lira,
    canción pindárica); Canción (otras formas) (para las composiciones que no se pueden
    adscribir a los casos detallados supra: ej. las canciones en cuartetos de endecasílabos,
    las canzonette chiabresche, etc.); Estribote; glosa (incluye todas las formas métricas
    en las que se puede desarrollar una glosa); Letra/Mote (se utilizará solo en los casos
    en los que la composición no tiene desarrollo estrófico; si lo tiene se utilizará la
    forma más adecuada entre: canción en arte menor, villancico, glosa); Madrigal; Octava
    real; Ovillejo; Pareados; Polimetría (incluye ensaladas y composiciones que tienen un
    esquema métrico variable que no se puede remitir a una estructura métrica; NB no incluye
    los romances y romancillos con desfecha final); Sextina; Soneto; Silva; Tercetos
    encadenados; Romance; Romancillo (tanto heptasílabo como hexasílabo);
    Romance/Romancillo con desfecha; Villancico (incluye los villancicos con coplas
    zejelescas).
  </p>
</section>

<section>
  <h2>Actualización de los datos</h2>
  <p>
    Las fichas y las referencias bibliográficas se actualizan a través de controles
    periódicos y por efecto de sugerencias y señalaciones de los usuarios.
  </p>
</section>
