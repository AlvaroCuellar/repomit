<section>
  <h2>Cómo consultar el repertorio</h2>
  <p>
    El usuario puede consultar el repertorio alfabético, acceder a las fichas de los
    manuscritos catalogados o utilizar la búsqueda por íncipit, verso, epígrafe,
    estribillo, autor y texto libre.
  </p>
  <p>
    La grafía de los poemas, salvo excepciones justificadas, sigue las normas ortográficas
    actuales. La búsqueda ignora puntuación, mayúsculas y tildes.
  </p>
  <p>También se pueden seleccionar los poemas catalogados conforme a su forma métrico-poética.</p>
  <p>
    Para una consulta más eficaz y provechosa del repertorio, se invitan los usuarios a
    consultar los <a href="/criterios">Criterios de catalogación</a>.
  </p>
</section>

