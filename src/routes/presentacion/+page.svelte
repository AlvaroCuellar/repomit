<h1>Presentación</h1>

<section>
  <h2>Qué es RePoMIt</h2>
  <p>
    RePoMIt, <em>Repertorio de la poesía en castellano en manuscritos italianos</em>,
    es un repertorio digital dedicado a la catalogación de las composiciones poéticas
    en castellano de los siglos XVI y XVII conservadas en manuscritos que se compusieron
    y/o circularon en Italia durante el reino de los Austrias o, en menor medida, que
    llegaron a Italia por sucesivos desplazamientos y/o adquisiciones.
  </p>
  <p>
    Su contenido y su infraestructura digital se actualizan a medida que se incorporan
    nuevos testimonios.
  </p>
</section>

<section>
  <h2>Origen del proyecto</h2>
  <p>
    El repertorio se diseñó y desarrolló en el marco del proyecto didáctico
    <em>Corre manuscrita (en Italia): Fuentes, métodos y herramientas para el estudio de
    la poesía áurea</em> (proyectos Fu.His.It. 2026) coordinado por Antonietta Molinaro
    (Università eCampus), con la participación de Álvaro Cuéllar (Universitat Autònoma
    de Barcelona).
  </p>
  <p>
    El proyecto didáctico, en forma de seminario, se dirigió a los estudiantes de Máster
    y Doctorado en universidades italianas durante el año académico 2025/2026. Vio la
    participación de 20 asistentes, quienes contribuyeron a catalogar el primer núcleo de
    seis testimonios manuscritos, custodiados en distintas bibliotecas italianas.
  </p>
</section>

<section>
  <h2>Objetivos</h2>
  <p>
    El objetivo principal de RePoMIt es ofrecer una vía de acceso ordenada y verificable
    a los testimonios manuscritos italianos que transmiten poesía en castellano de los
    Siglos de Oro. A cada poema le corresponde una ficha en la que se proporcionan datos
    textuales y bibliográficos esenciales y, en algunos casos, la transcripción completa
    del texto.
  </p>
  <p>
    En su primera fase de desarrollo, RePoMIt privilegia la catalogación de testimonios
    manuscritos que se custodien en bibliotecas de las que todavía no existen catálogos
    completos del patrimonio manuscrito. Sin embargo, por incluir más datos que un
    repertorio tradicional, está abierto a acoger también testimonios que proceden de
    bibliotecas ya catalogadas.
  </p>
</section>

