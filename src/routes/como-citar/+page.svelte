<h1>Cómo citar el repertorio</h1>

<section>
  <h2>El repertorio completo</h2>
  <p>La referencia debe indicar la dirección científica, el título completo del repertorio, su dirección electrónica y la fecha de consulta:</p>
  <blockquote>Molinaro, Antonietta (dir.), <em>RePoMIt. Repertorio de la poesía en castellano en manuscritos italianos</em>, <a href="https://repomit.vercel.app/">https://repomit.vercel.app/</a> [consulta: día, mes y año].</blockquote>
</section>

<section>
  <h2>Una ficha de poema</h2>
  <p>Se indicarán las personas responsables de la ficha, el íncipit del poema, el número de ítem y el enlace directo. Si consta una fecha de última revisión, se añadirá también:</p>
  <blockquote>Apellido, Nombre [responsable de la ficha], «Íncipit del poema», ítem [identificador], en Antonietta Molinaro (dir.), <em>RePoMIt. Repertorio de la poesía en castellano en manuscritos italianos</em>, última revisión: [fecha], [enlace directo a la ficha] [consulta: día, mes y año].</blockquote>
  <p>La persona responsable de la ficha no debe confundirse con el autor al que se atribuye el poema. Si hay varios responsables, se incluirán todos. Si no consta ninguno, la referencia comenzará por el íncipit; si no consta fecha de revisión, se omitirá ese dato.</p>
</section>

<section>
  <h2>Una ficha de manuscrito</h2>
  <p>Se sustituirá el íncipit por la sigla del manuscrito y la identificación de la biblioteca y la signatura. No es necesario añadir un número de ítem de poema:</p>
  <blockquote>Apellido, Nombre [responsable de la ficha], «[Sigla del manuscrito]: [ciudad, biblioteca, signatura]», en Antonietta Molinaro (dir.), <em>RePoMIt. Repertorio de la poesía en castellano en manuscritos italianos</em>, última revisión: [fecha], [enlace directo a la ficha] [consulta: día, mes y año].</blockquote>
  <p>Se aplicarán las mismas indicaciones sobre responsables y fecha de revisión que en las fichas de poemas.</p>
</section>

